#!/usr/bin/env bash
#
# Compares the config on the droplet with the copies kept in this directory.
#
#   ./snapshot.sh            report drift; refresh "pull" files; never touch "check" files
#   ./snapshot.sh --adopt    same, and overwrite drifted "check" files with the server's copy
#
# `manifest` (next to this script) lists one file per line:
#
#   <check|pull>  <path on the server>  <path relative to this directory>
#
#   check  the repo is the source of truth (applied to the server by hand or through the
#          Forge UI). Drift = the server differs from the repo, ignoring comments, blank
#          lines, indentation and the numeric cert id Forge rewrites on every renewal.
#   pull   the server is the source of truth (generated by Forge or the OS); the local
#          copy is a reference snapshot, refreshed on every run.
#
# Read-only on the server (only `cat` over SSH), all over a single multiplexed connection
# (one login instead of one per file). Exit status is 1 if any "check"
# file drifted or any file couldn't be read, 2 if the host can't be reached.
# Override the host with INFRA_HOST.

set -euo pipefail
cd "$(dirname "$0")"

host="${INFRA_HOST:-forge@do}"
adopt=0
[[ "${1:-}" == "--adopt" ]] && adopt=1

ctl="$(mktemp -u "${TMPDIR:-/tmp}/snapshot.XXXXXX")"
ssh_opts=(-o BatchMode=yes -o ControlMaster=auto -o "ControlPath=$ctl" -o ControlPersist=30)
trap 'ssh "${ssh_opts[@]}" -O exit "$host" 2>/dev/null || true' EXIT

strip() {
  sed -E 's#/[0-9]+/server\.(crt|key)#/<cert-id>/server.\1#; s/[[:space:]]+#.*$//; /^[[:space:]]*[#;]/d; s/^[[:space:]]+//; s/[[:space:]]+$//; /^$/d' "$1" | awk '{print}'
}

status=0
while read -r mode remote local; do
  [[ -z "${mode:-}" || "$mode" == \#* ]] && continue
  tmp="$(mktemp)"
  rc=0
  ssh -n "${ssh_opts[@]}" "$host" "cat '$remote'" >"$tmp" 2>/dev/null || rc=$?
  if [[ $rc -eq 255 ]]; then
    echo "!! cannot reach $host"
    rm -f "$tmp"
    exit 2
  elif [[ $rc -ne 0 ]]; then
    echo "!! cannot read $remote"
    status=1
    rm -f "$tmp"
    continue
  fi

  case "$mode" in
    pull)
      if [[ -f "$local" ]] && cmp -s "$tmp" "$local"; then
        echo "ok      $local"
      else
        mkdir -p "$(dirname "$local")"
        cp "$tmp" "$local"
        echo "pulled  $local"
      fi
      ;;
    check)
      if [[ ! -f "$local" ]]; then
        echo "missing $local (server has $remote)"
        status=1
        if [[ $adopt -eq 1 ]]; then mkdir -p "$(dirname "$local")"; cp "$tmp" "$local"; echo "  adopted"; fi
      elif out="$(diff -u --label "repo:$local" --label "server:$remote" <(strip "$local") <(strip "$tmp"))"; then
        echo "ok      $local"
      else
        echo "DRIFT   $local"
        echo "$out" | sed 's/^/  /'
        status=1
        if [[ $adopt -eq 1 ]]; then cp "$tmp" "$local"; echo "  adopted the server's copy"; fi
      fi
      ;;
    *)
      echo "!! bad mode '$mode' in manifest"
      status=1
      ;;
  esac
  rm -f "$tmp"
done <manifest

exit $status
